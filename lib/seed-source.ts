import { DEFAULT_SETTINGS } from './settings-schema';
import { buildClaudeSystem } from './tone';
import { DEFAULT_CHAT_GREETING, DEFAULT_EMAIL_SIGNATURE, DEFAULT_GEMINI_REVIEWER, DEFAULT_HOLDING_MESSAGE } from './default-prompts';
import { SAMPLE_FAQ } from './sample-faq';
import { toCsv } from './csv';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const NOW = "strftime('%Y-%m-%dT%H:%M:%fZ', 'now')";

export const DEFAULT_PROMPTS = (): { id: string; name: string; body: string }[] => [
  { id: 'claude_system', name: 'Assistant instructions (Claude)', body: buildClaudeSystem(DEFAULT_SETTINGS) },
  { id: 'gemini_reviewer', name: 'Reviewer instructions (Gemini)', body: DEFAULT_GEMINI_REVIEWER },
  { id: 'holding_message', name: 'Message when a person needs to help', body: DEFAULT_HOLDING_MESSAGE },
  { id: 'email_signature', name: 'Email signature', body: DEFAULT_EMAIL_SIGNATURE },
  { id: 'chat_greeting', name: 'Chat greeting', body: DEFAULT_CHAT_GREETING },
];

/** seeds/sample-data.sql: default settings, default tone and instructions, 12 sample answers. Never overwrites existing rows. */
export function buildSeedSql(): string {
  const lines: string[] = [
    '-- Sample data loaded automatically the first time the panel starts.',
    '-- Generated by scripts/generate-seed.ts from lib/ defaults. Every statement keeps existing rows.',
    '',
    '-- Default settings (the same values as lib/settings-schema.ts).',
  ];
  for (const [k, v] of Object.entries(DEFAULT_SETTINGS)) {
    lines.push(`INSERT OR IGNORE INTO settings (key, value_json, updated_at, updated_by) VALUES (${q(k)}, ${q(JSON.stringify(v))}, ${NOW}, 'system');`);
  }
  lines.push('', '-- Default tone (Friendly) and instructions, version 1.');
  for (const p of DEFAULT_PROMPTS()) {
    lines.push(`INSERT OR IGNORE INTO prompts (id, name, body, version, updated_at, updated_by) VALUES (${q(p.id)}, ${q(p.name)}, ${q(p.body)}, 1, ${NOW}, 'system');`);
    lines.push(`INSERT OR IGNORE INTO prompt_versions (prompt_id, version, body, changed_by, changed_at, note) VALUES (${q(p.id)}, 1, ${q(p.body)}, 'system', ${NOW}, 'Recommended default');`);
  }
  lines.push('', '-- 12 sample answers for a fictional shop, only if there are no answers yet.');
  lines.push(`INSERT INTO faq (question, answer, tags, active, updated_at)\n  SELECT column1, column2, column3, 1, ${NOW} FROM (VALUES\n${SAMPLE_FAQ.map((f) => `    (${q(f.question)}, ${q(f.answer)}, ${q(f.keywords)})`).join(',\n')}\n  ) WHERE NOT EXISTS (SELECT 1 FROM faq);`);
  return `${lines.join('\n')}\n`;
}

/** docs/sample-faq.csv: the import template, filled with the sample answers. */
export function buildSampleCsv(): string {
  return toCsv(['question', 'reply', 'keywords', 'use_this_answer'], SAMPLE_FAQ.map((f) => [f.question, f.answer, f.keywords.split(',').join(', '), 'yes']));
}
