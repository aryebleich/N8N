// Embeds migrations/*.sql and seeds/sample-data.sql into TypeScript modules so the
// standalone build (Docker, Vercel) can run them without the .sql files on disk.
// Runs automatically before `npm run build`, `npm run dev` and `npm test`.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const files = readdirSync(path.join(root, 'migrations')).filter((f) => /^\d{3}_.+\.sql$/.test(f)).sort();
const migrations = files.map((name) => ({ name, sql: readFileSync(path.join(root, 'migrations', name), 'utf8') }));
writeFileSync(path.join(root, 'lib', 'migrations-bundle.ts'), `// Generated by scripts/bundle-sql.mjs from migrations/*.sql. Do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(migrations, null, 2)};\n`);
const seed = readFileSync(path.join(root, 'seeds', 'sample-data.sql'), 'utf8');
writeFileSync(path.join(root, 'lib', 'seed-bundle.ts'), `// Generated by scripts/bundle-sql.mjs from seeds/sample-data.sql. Do not edit.\nexport const SEED_VERSION = 1;\nexport const SEED_SQL: string = ${JSON.stringify(seed)};\n`);
console.log(`bundled ${files.length} migrations and the seed file`);
